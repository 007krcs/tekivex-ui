#!/usr/bin/env node
/**
 * emit-dts-shims.mjs — write the per-entry .d.ts files referenced by
 * package.json `exports[*].types`.
 *
 * Why this exists:
 *   `tsc --emitDeclarationOnly` (with the project's existing tsconfig) emits
 *   declarations into `dist/src/<entry>/index.d.ts`, not into the flat
 *   `dist/<entry>.d.ts` paths that `package.json` `exports` references.
 *   Without these shims, TypeScript consumers importing from a subpath
 *   (e.g. `import { TkxLineChart } from 'tekivex-ui/charts'`) get TS2307
 *   "Cannot find module" — runtime works, types break.
 *
 *   v3.18.0 shipped without these shims (they were created manually before
 *   publish but `prepublishOnly` re-ran `npm run build` and wiped them just
 *   before the tarball went up). v3.18.1 fixes the build pipeline so the
 *   shims are always present in `dist/`.
 *
 * Strategy:
 *   For each public subpath entry, write a thin re-export shim:
 *     `export * from './src/<entry>/index';`
 *   These resolve to the real declarations under `dist/src/`.
 *
 * Run as the LAST step of `npm run build` so the dist is complete before
 * `npm pack` / `npm publish` see it.
 */

import { writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DIST = resolve(__dirname, '..', 'dist');

if (!existsSync(DIST)) {
  console.error('✗ dist/ missing — run `npm run build` first');
  process.exit(1);
}

// Must mirror the `entries` map in vite.config.ts and the `exports`
// declarations in package.json. Keep these three in sync.
const ENTRIES = [
  { name: 'themes',       src: './src/themes/index' },
  { name: 'charts',       src: './src/charts/index' },
  { name: 'headless',     src: './src/headless/index' },
  { name: 'i18n',         src: './src/i18n/index' },
  { name: 'quantum',      src: './src/quantum/index' },
  { name: 'realtime',     src: './src/realtime/index' },
  { name: 'agent',        src: './src/agent/index' },
  { name: 'experimental', src: './src/experimental/index' },
];

console.log('Writing subpath type shims:');

let written = 0;
let skipped = 0;

for (const { name, src } of ENTRIES) {
  const target = resolve(DIST, `${name}.d.ts`);

  // The shim only works if the underlying declaration file exists.
  // We check `dist/src/<entry>/index.d.ts` — if tsc didn't emit it
  // (e.g. the entry source folder is empty / had errors), warn loudly
  // and exit non-zero so CI catches it.
  const targetDecl = resolve(DIST, src.slice(2) + '.d.ts');
  if (!existsSync(targetDecl)) {
    console.warn(`  ⚠ skipping ${name} — backing declaration missing at ${targetDecl}`);
    skipped++;
    continue;
  }

  const content =
    `// Auto-generated by scripts/emit-dts-shims.mjs — re-exports the per-entry\n` +
    `// declarations that tsc emits under dist/src/. See package.json exports.\n` +
    `export * from '${src}';\n`;

  writeFileSync(target, content);
  console.log(`  ✓ dist/${name}.d.ts → ${src}`);
  written++;
}

console.log(`\n${written} shim(s) written, ${skipped} skipped.`);

if (skipped > 0) {
  console.error(
    `\n✗ ${skipped} subpath(s) have a missing backing declaration. ` +
      `Either the entry source is empty, tsc errored on it, or the entry was ` +
      `removed from package.json exports. Aborting so we don't publish a ` +
      `tarball with broken types.`,
  );
  process.exit(1);
}
