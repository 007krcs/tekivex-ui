// ── Locale strings ──────────────────────────────────────────────────────────

export interface LocaleStrings {
  // Common
  close: string;
  cancel: string;
  confirm: string;
  save: string;
  delete: string;
  search: string;
  loading: string;
  noResults: string;
  required: string;

  // Pagination
  previous: string;
  next: string;
  pageOf: (page: number, total: number) => string;

  // Select
  selectPlaceholder: string;
  clearSelection: string;

  // DatePicker
  selectDate: string;
  today: string;

  // FileUpload
  dropFiles: string;
  browse: string;

  // Table / DataGrid
  noData: string;
  sortAscending: string;
  sortDescending: string;
  filterPlaceholder: string;
  exportCsv: string;
  rowsSelected: (n: number) => string;

  // Pagination — optional, English fallback used at the call site if missing.
  // (Optional so adding these does not break the 35 existing locale literals.)
  firstPage?: string;
  lastPage?: string;
  previousPage?: string;
  nextPage?: string;
  showingRange?: (start: number, end: number, total: number) => string;
  itemsPerPage?: string;

  // FileUpload extras
  uploadFiles?: string;
  acceptedFormats?: (formats: string) => string;
  maxFileSize?: (size: string) => string;

  // DatePicker extras
  clearDate?: string;
  previousMonth?: string;
  nextMonth?: string;
  yesterday?: string;
  last7Days?: string;
  last30Days?: string;
  thisMonth?: string;
  lastMonth?: string;

  // Toast / notifications
  notifications?: string;

  // Command palette
  commandSearch?: string;
  noCommandsFound?: string;

  // Drawer
  closeDrawer?: string;

  // Form validation
  fieldRequired?: string;
  invalidFormat?: string;
  minLength?: (n: number) => string;
  maxLength?: (n: number) => string;
  minValue?: (n: number) => string;
  maxValue?: (n: number) => string;

  // DataGrid extras
  noRows?: string;
  resetFilters?: string;

  // NumberInput
  increment?: string;
  decrement?: string;

  // OTP
  oneTimePassword?: string;

  // Breadcrumb
  breadcrumb?: string;
  showHiddenItems?: string;

  // RichTextDisplay
  richTextContent?: string;
}

// ── Helper — build a locale without having to re-type every key ─────────────

function locale(strings: LocaleStrings): LocaleStrings {
  return strings;
}

